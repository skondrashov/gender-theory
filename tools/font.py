#!/usr/bin/env python
"""The lattice font: tools/font.json (the owner's table, drawn connect-the-dots in one cell) →
app/src/scenes/font.rs, the table the `text` kind draws from.

    python tools/font.py            # regenerate font.rs

A glyph is strokes between points of a grid inside a cell — `grid` [across, down] points,
x 0 at the left, y 0 at the bottom; a stroke of no length is a dot. `w`/`h` are how much of
the cell the point grid spans (the kind's defaults), `center` whether each glyph is shifted
so the middle of what it draws is the cell's middle. Keys are characters; capitals and small
letters are separate glyphs. Pure Python.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'font.json')
OUT = os.path.join(ROOT, 'app', 'src', 'scenes', 'font.rs')

font = json.load(open(SRC, encoding='utf-8'))
cols, rows = font['grid']
glyphs = sorted(font['glyphs'].items(), key=lambda kv: ord(kv[0]))

lines = [
    '// Generated by tools/font.py from tools/font.json — the owner\'s lattice font. Don\'t edit;',
    '// change the JSON (the connect-the-dots page writes it) and rerun the tool.',
    '',
    '/// Points across and down inside a cell, minus one: a glyph coordinate runs 0..=COLS, 0..=ROWS.',
    f'pub const COLS: f32 = {cols - 1}.0;',
    f'pub const ROWS: f32 = {rows - 1}.0;',
    '/// How much of the cell the point grid spans by default, across and down.',
    f'pub const WIDTH: f32 = {float(font.get("w", 1))};',
    f'pub const HEIGHT: f32 = {float(font.get("h", 1))};',
    '/// Whether each glyph is shifted to the middle of its cell by default.',
    f'pub const CENTER: bool = {"true" if font.get("center", True) else "false"};',
    '',
    '/// Strokes [x1, y1, x2, y2] in grid points, per character, sorted by character.',
    'pub static GLYPHS: &[(char, &[[u8; 4]])] = &[',
]
for ch, strokes in glyphs:
    if not strokes:
        continue
    assert all(0 <= s[0] < cols and 0 <= s[2] < cols and 0 <= s[1] < rows and 0 <= s[3] < rows for s in strokes), ch
    body = ', '.join('[%d, %d, %d, %d]' % tuple(s) for s in strokes)
    c = repr(ch).replace('"', '\\"') if ch != "'" else "'\\''"
    lines.append(f'\t({c}, &[{body}]),')
lines += [
    '];',
    '',
    '/// A character\'s strokes; a capital or small letter not drawn borrows the other case.',
    'pub fn glyph(c: char) -> Option<&\'static [[u8; 4]]> {',
    '\tlet find = |c: char| GLYPHS.binary_search_by_key(&c, |g| g.0).ok().map(|k| GLYPHS[k].1);',
    '\tfind(c).or_else(|| {',
    '\t\tlet other: String = if c.is_lowercase() { c.to_uppercase().collect() } else { c.to_lowercase().collect() };',
    '\t\tother.chars().next().filter(|&o| o != c).and_then(find)',
    '\t})',
    '}',
    '',
    '/// How far across (in grid points) to move a glyph so the middle of what it draws is the',
    '/// cell\'s middle.',
    'pub fn shift(strokes: &[[u8; 4]]) -> f32 {',
    '\tlet (lo, hi) = strokes.iter().fold((u8::MAX, u8::MIN), |(lo, hi), s| (lo.min(s[0]).min(s[2]), hi.max(s[0]).max(s[2])));',
    '\tCOLS / 2.0 - (lo as f32 + hi as f32) / 2.0',
    '}',
    '',
]
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(f'{OUT}: {len(glyphs)} glyphs on a {cols} × {rows} grid')
